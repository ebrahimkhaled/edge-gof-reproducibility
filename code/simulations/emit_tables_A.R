cat(sprintf("HL    cloglog G=10 power: p*=3 %.3f -> p*=20 %.3f  (drop %.3f, %.0f%% relative)\n",
    h$power_adj[h$pstar == 3], h$power_adj[h$pstar == 20],
    h$power_adj[h$pstar == 3] - h$power_adj[h$pstar == 20],
    100 * (1 - h$power_adj[h$pstar == 20] / h$power_adj[h$pstar == 3])))
sz <- S[S$scenario == "cloglog" & S$test %in% ORD, ]
cat(sprintf("size range over ALL tests, p* and G: %.4f to %.4f (nominal 0.05, MCSE 0.0049)\n",
    min(sz$size_raw), max(sz$size_raw)))
edg <- sz[grepl("EDGE", sz$test), ]
cat(sprintf("size range for the EDGE bases only:  %.4f to %.4f  -> max %.1f MCSE from nominal\n",
    min(edg$size_raw), max(edg$size_raw), max(abs(edg$size_raw - .05)) / 0.00487))
st <- S[S$test == "Stukel" & S$scenario == "cloglog", ]
es <- S[S$test == "EDGE.stk" & S$scenario == "cloglog", ]
cat(sprintf("decline rate: Stukel %.1f%%-%.1f%%  vs EDGE-stk %.2f%%-%.2f%%\n",
    100 * min(st$na_alt), 100 * max(st$na_alt), 100 * min(es$na_alt), 100 * max(es$na_alt)))
