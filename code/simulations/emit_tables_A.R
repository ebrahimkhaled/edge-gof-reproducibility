cat(sprintf("EDGE3 cloglog G=10 power: p*=3 %.3f -> p*=20 %.3f  (drop %.3f, %.0f%% relative)\n",
    e$power_adj[e$pstar == 3], e$power_adj[e$pstar == 20],
